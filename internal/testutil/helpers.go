// SetupTestRouter creates a test gin router with no logger
func SetupTestRouter() *gin.Engine {
	gin.SetMode(gin.TestMode)
	r := gin.New()
	r.Use(gin.Recovery())
	return r
}

// MakeRequest creates a test HTTP request
func MakeRequest(method, path string, body string) *http.Request {
	req := httptest.NewRequest(method, path, strings.NewReader(body))
	req.Header.Set("Content-Type", "application/json")
	return req
}

// MakeRequestWithHeaders creates a test HTTP request with custom headers
func MakeRequestWithHeaders(method, path string, body string, headers map[string]string) *http.Request {
	req := MakeRequest(method, path, body)
	for k, v := range headers {
		req.Header.Set(k, v)
	}
	return req
}

